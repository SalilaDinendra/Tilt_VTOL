%% Export ABCD matrices to ArduPilot C++ header

filename = '/home/salilaubuntu/ardupilot/libraries/APM_Control/q_hinf_matrices.h';

% Verify SISO state-space dimensions
assert(rows(A) == columns(A), 'A must be square');
assert(rows(B) == n && columns(B) == 1, 'B must be n x 1');
assert(rows(C) == 1 && columns(C) == n, 'C must be 1 x n');
assert(isscalar(D), 'D must be scalar');

% Check for invalid values
assert(all(isfinite(A(:))) && all(isfinite(B(:))) && ...
       all(isfinite(C(:))) && isfinite(D), ...
       'Controller contains invalid coefficients');

fid = fopen(filename, 'w');
assert(fid >= 0, 'Unable to open output file');
fprintf(fid, '#pragma once\n\n');
fprintf(fid, '// Automatically generated by GNU Octave\n');
fprintf(fid, '// Discrete H-infinity pitch-rate controller\n\n');
fprintf(fid, 'namespace QHinf {\n\n');

% Controller order
fprintf(fid, 'static constexpr int N = %d;\n', n);
% Sample time
fprintf(fid, 'static constexpr double Ts = %.17g;\n\n', Ts);
%% Matrix A
fprintf(fid, 'static constexpr double A[N][N] = {\n');

for i = 1:n
    fprintf(fid, '    {');
    for j = 1:n
        fprintf(fid, '%.17g', A(i,j));
        if j < n
            fprintf(fid, ', ');
        end
    end
    fprintf(fid, '}');
    if i < n
        fprintf(fid, ',');
    end
    fprintf(fid, '\n');
end

fprintf(fid, '};\n\n');


%% Matrix B
fprintf(fid, 'static constexpr double B[N] = {');

for i = 1:n
    fprintf(fid, '%.17g', B(i));
    if i < n
        fprintf(fid, ', ');
    end
end

fprintf(fid, '};\n\n');


%% Matrix C
fprintf(fid, 'static constexpr double C[N] = {');

for i = 1:n
    fprintf(fid, '%.17g', C(i));
    if i < n
        fprintf(fid, ', ');
    end
end

fprintf(fid, '};\n\n');


%% Matrix D
fprintf(fid, 'static constexpr double D = %.17g;\n\n', D);
fprintf(fid, '} // namespace QHinf\n');
fclose(fid);
disp('H-infinity controller exported successfully');
disp(filename);